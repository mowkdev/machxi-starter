#!/usr/bin/env node
// The open lanes, one file each (ADR-0082 §4 and §5, a delta on ADR-0079 §2).
//
// Each open lane is `docs/plan/lanes/D<n>.md`: the deliverable and its plan,
// the date it opened, the branch it builds on, its tier, whether it adds
// migrations, and its records. `/scope` creates the file when a lane opens and
// `/ship` removes it when the lane ships, so two lanes opening or shipping
// touch two files rather than one list.
//
// The ledger's window section carries the list of those files and the running
// paragraph under it, and both are generated here, between two markers, from
// the files alone. A lane never edits the block by hand; a merge that
// conflicts in it is resolved by running this script, the way a digest is
// regenerated (ADR-0079 §4). `pnpm docs:check` renders the block again and
// refuses a ledger whose block differs (`scripts/docs-hygiene.mjs`).
//
// Usage:
//   node scripts/lanes.mjs     write the block; exit 1 if a lane file does not parse

import { existsSync } from "node:fs";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

/** The ledger whose window section carries the generated block. */
export const LEDGER = "docs/plan/README.md";

/** Where the open lanes live, one file each. */
export const LANES_DIR = "docs/plan/lanes";

/** A plan header's and a lane file's tier (ADR-0082 §5). */
export const TIERS = ["package", "api", "schema"];

export const BLOCK_BEGIN =
  "<!-- Generated by `pnpm lanes` from docs/plan/lanes/ — never edited by hand; `pnpm docs:check` refuses it stale. -->";
export const BLOCK_END = "<!-- End of the generated lanes. -->";

/** `D34.md` — the one name a lane file takes. */
const LANE_FILE = /^(D\d+)\.md$/;

/** `- Key: value` — a field of a lane file. */
const FIELD = /^- ([A-Z][a-z]+): (.*)$/;

/** `[D34](../0034-lanes-on-one-machine.md)` — the deliverable and its plan. */
const DELIVERABLE = /^\[(D\d+)\]\(\.\.\/(\d{4}-[a-z0-9-]+\.md)\)$/;

/**
 * `[0079](../../adr/0079-….md)` — a record as a lane file links it, the label
 * and the file agreeing. The field is nothing but these, joined by `, `: a
 * record written any other way would escape the disjointness check.
 */
const RECORD = /^\[(\d{4})\]\(\.\.\/\.\.\/adr\/((\d{4})-[^)]+\.md)\)$/;

const FIELDS = ["Deliverable", "Opened", "Branch", "Tier", "Schema", "Records"];

export const LANE_SHAPE =
  "a lane file is `docs/plan/lanes/D<n>.md` with one line each of `- Deliverable: [D<n>](../<plan>.md)`, `- Opened: YYYY-MM-DD`, `- Branch: `<branch>``, `- Tier: package|api|schema`, `- Schema: yes|no` and `- Records: [NNNN](../../adr/NNNN-….md), …`";

/**
 * Reads one lane file. Returns `{ lane }`, or `{ malformed }` naming each line
 * that does not parse — a typo refused rather than read as fewer records.
 * Above the first field the title and a sentence of prose are not read; from
 * the first field on, every non-blank line is a field, and an indented line
 * anywhere is refused, so a record continued or nested onto a line of its own
 * cannot escape the disjointness check.
 */
export function parseLaneFile(name, text) {
  const malformed = [];
  const bad = (line, found, why) =>
    malformed.push({ line, found: found.slice(0, 60), why });
  const file = name.match(LANE_FILE);
  if (!file) {
    bad(1, name, "the file is named `D<n>.md`");
    return { malformed };
  }
  const fields = new Map();
  text.split(/\r?\n/).forEach((raw, index) => {
    const line = raw.trimEnd();
    if (line === "") return;
    if (/^\s/.test(line)) {
      bad(
        index + 1,
        line.trim(),
        "an indented line; a lane file's lines start at the margin",
      );
      return;
    }
    if (!line.startsWith("- ") && fields.size === 0) return;
    const m = line.match(FIELD);
    if (!m || !FIELDS.includes(m[1])) {
      bad(index + 1, line, "not a field of the lane's shape");
      return;
    }
    if (fields.has(m[1])) {
      bad(index + 1, line, `a second \`${m[1]}\` line`);
      return;
    }
    fields.set(m[1], { line: index + 1, value: m[2].trim() });
  });
  for (const key of FIELDS) {
    if (!fields.has(key)) bad(1, name, `no \`- ${key}:\` line`);
  }
  if (malformed.length > 0) return { malformed };

  const at = (key) => fields.get(key);
  const deliverable = at("Deliverable").value.match(DELIVERABLE);
  // The plan's file opens with the deliverable's number, zero-padded: `D34`
  // links `0034-…`, so the tier is read from this lane's plan and no other.
  const padded = file[1].slice(1).padStart(4, "0");
  if (
    !deliverable ||
    deliverable[1] !== file[1] ||
    !deliverable[2].startsWith(`${padded}-`)
  ) {
    bad(
      at("Deliverable").line,
      at("Deliverable").value,
      `names the deliverable its file is named for, ${file[1]}, and links its plan, \`../${padded}-….md\``,
    );
  }
  const opened = at("Opened").value;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(opened)) {
    bad(at("Opened").line, opened, "a date, YYYY-MM-DD");
  }
  const branch = at("Branch").value.match(/^`([^`\s]+)`$/);
  if (!branch) {
    bad(at("Branch").line, at("Branch").value, "one backticked branch name");
  }
  const tier = at("Tier").value;
  if (!TIERS.includes(tier)) {
    bad(at("Tier").line, tier, `one of ${TIERS.join(", ")}`);
  }
  const schema = at("Schema").value;
  if (schema !== "yes" && schema !== "no") {
    bad(at("Schema").line, schema, "yes or no");
  }
  const records = at("Records")
    .value.split(", ")
    .map((part) => part.match(RECORD));
  if (records.some((m) => !m || m[1] !== m[3])) {
    bad(
      at("Records").line,
      at("Records").value,
      "records are `[NNNN](../../adr/NNNN-….md)` links joined by `, `",
    );
  }
  if (malformed.length > 0) return { malformed };

  return {
    lane: {
      deliverable: file[1],
      plan: deliverable[2],
      opened,
      branch: branch[1],
      tier,
      schema: schema === "yes",
      records: records.map((m) => ({ id: m[1], file: m[2] })),
      fields: Object.fromEntries(
        [...fields].map(([key, { line }]) => [key, line]),
      ),
    },
  };
}

/** `D9` before `D34`: lanes in the order their deliverables are numbered. */
const byNumber = (a, b) =>
  Number(a.deliverable.slice(1)) - Number(b.deliverable.slice(1));

const WORDS = [
  "No",
  "One",
  "Two",
  "Three",
  "Four",
  "Five",
  "Six",
  "Seven",
  "Eight",
  "Nine",
];
const count = (n) => WORDS[n] ?? String(n);

const andList = (items) =>
  items.length <= 1
    ? items.join("")
    : `${items.slice(0, -1).join(", ")} and ${items.at(-1)}`;

/**
 * The block the window section carries: one list item per lane file, linked,
 * and the running paragraph — the state the files say, and nothing a file
 * does not. The history of each window is the ledger's `How D<n> opened` and
 * `How D<n> closed` sections, never this paragraph.
 */
export function renderLanes(lanes) {
  const sorted = [...lanes].sort(byNumber);
  const items = sorted.map(
    (lane) =>
      `- **Lane [${lane.deliverable}](${lane.plan})** ([lane file](lanes/${lane.deliverable}.md)) — opened ${lane.opened} · branch \`${lane.branch}\` · tier: ${lane.tier} · schema: ${lane.schema ? "yes" : "no"} · records ${lane.records
        .map((r) => `[${r.id}](../adr/${r.file})`)
        .join(", ")}`,
  );

  const names = sorted.map((l) => l.deliverable);
  const sentences = [];
  if (sorted.length === 0) {
    sentences.push(
      "**No lane is open.** Every record is closed: change any of them only by supersession.",
    );
  } else {
    const one = sorted.length === 1;
    sentences.push(
      `**${count(sorted.length)} lane${one ? " is" : "s are"} open: ${andList(names)}.**`,
      one
        ? "The records it lists may be amended in place, labelled, while it is in progress; every other record is closed and changes only by supersession."
        : "The records each lists may be amended in place, labelled, while that lane is in progress, and no record is in two lanes; every other record is closed and changes only by supersession.",
    );
    const schema = sorted.filter((l) => l.schema);
    sentences.push(
      schema.length === 0
        ? "No open lane adds migrations."
        : `${andList(schema.map((l) => l.deliverable))} owns the schema; no other open lane adds migrations.`,
    );
    const tiers = TIERS.map((tier) => [
      tier,
      sorted.filter((l) => l.tier === tier).map((l) => l.deliverable),
    ]).filter(([, ds]) => ds.length > 0);
    sentences.push(
      `By tier: ${tiers.map(([tier, ds]) => `\`${tier}\` ${andList(ds)}`).join("; ")}.`,
    );
  }

  return [
    BLOCK_BEGIN,
    "",
    ...(items.length > 0 ? [...items, ""] : []),
    sentences.join(" "),
    "",
    BLOCK_END,
  ].join("\n");
}

/**
 * Where the block sits in the ledger, or `null` when the markers are absent.
 * A marker that appears twice, or out of order, is `{ error }`.
 */
export function findBlock(text) {
  const begin = text.indexOf(BLOCK_BEGIN);
  const end = text.indexOf(BLOCK_END);
  if (begin === -1 && end === -1) return null;
  if (
    begin === -1 ||
    end === -1 ||
    end < begin ||
    text.indexOf(BLOCK_BEGIN, begin + 1) !== -1 ||
    text.indexOf(BLOCK_END, end + 1) !== -1
  ) {
    return {
      error: "the generated block's two markers appear once each, in order",
    };
  }
  return {
    start: begin,
    end: end + BLOCK_END.length,
    block: text.slice(begin, end + BLOCK_END.length),
  };
}

/** The ledger with its block replaced by `block`. */
export function applyBlock(text, block) {
  const found = findBlock(text);
  if (found === null) {
    throw new Error(
      `${LEDGER} has no generated block in its window section; put the two markers there:\n${BLOCK_BEGIN}\n${BLOCK_END}`,
    );
  }
  if (found.error) throw new Error(`${LEDGER}: ${found.error}`);
  return text.slice(0, found.start) + block + text.slice(found.end);
}

/** Every lane file, `{ rel, name, text }`, in name order. */
export async function readLaneFiles(root = repoRoot) {
  const dir = path.join(root, ...LANES_DIR.split("/"));
  if (!existsSync(dir)) return [];
  const names = (await readdir(dir))
    .filter((name) => name.endsWith(".md") && name !== "README.md")
    .sort();
  return Promise.all(
    names.map(async (name) => ({
      rel: `${LANES_DIR}/${name}`,
      name,
      text: await readFile(path.join(dir, name), "utf8"),
    })),
  );
}

/**
 * Writes the block from the files. Returns `{ wrote, lanes }`, or throws when
 * a lane file does not parse — the block is never written from a partial list.
 */
export async function writeLanes(root = repoRoot) {
  const files = await readLaneFiles(root);
  const lanes = [];
  const problems = [];
  for (const file of files) {
    const { lane, malformed } = parseLaneFile(file.name, file.text);
    if (lane) lanes.push(lane);
    for (const m of malformed ?? []) {
      problems.push(
        `${file.rel}:${m.line}  ${JSON.stringify(m.found)} — ${m.why}`,
      );
    }
  }
  if (problems.length > 0) {
    throw new Error(`${problems.join("\n")}\n\n${LANE_SHAPE}`);
  }
  const full = path.join(root, ...LEDGER.split("/"));
  const text = await readFile(full, "utf8");
  const next = applyBlock(text, renderLanes(lanes));
  if (next === text) return { wrote: false, lanes: lanes.length };
  await writeFile(full, next);
  return { wrote: true, lanes: lanes.length };
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    const { wrote, lanes } = await writeLanes();
    console.log(
      `lanes: ${wrote ? "wrote" : "unchanged"} ${LEDGER} (${lanes} open)`,
    );
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
